#!/usr/bin/env python3
"""Generate the versioned, cross-platform Q15 integer sigmoid constants."""
from decimal import Decimal, ROUND_HALF_UP, getcontext
from pathlib import Path

getcontext().prec = 80
q = Decimal(32768)
values = []
for coordinate in range(-2048, 2049):
    probability = q / (Decimal(1) + (-Decimal(coordinate) / 256).exp())
    rounded = int(probability.to_integral_value(rounding=ROUND_HALF_UP))
    values.append(min(32767, max(1, rounded)))

lines = ["// Generated by gen_tables.py; Q15 logistic z/256, Decimal(80), ROUND_HALF_UP.",
         "#pragma once", "#include <cstdint>",
         "inline constexpr uint16_t kSquash[4097] = {"]
for start in range(0, len(values), 16):
    lines.append("    " + ", ".join(str(v) for v in values[start:start + 16]) + ",")
lines.append("};")
Path(__file__).with_name("squash_table.h").write_text("\n".join(lines) + "\n")

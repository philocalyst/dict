#!/usr/bin/env python3
"""Fast adversarial tests for the quickbench harness.

These tests use a tiny trusted adapter fixture and direct ``measure`` calls so
they never launch the large corpus suite.  The worker is still a fresh Python
process for every encode/decode operation, which exercises the actual cache,
verification and logging boundary.
"""

from __future__ import annotations

import json
from pathlib import Path
import subprocess
import sys
import tempfile
import textwrap
import time
import unittest

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import bench  # noqa: E402


GOOD_ADAPTER = """
from pathlib import Path

def _count(path):
    if path:
        p = Path(path)
        p.write_text(str(int(p.read_text()) + 1) if p.exists() else "1")

def encode(data, block_bytes, counter=None, sleep=0, **options):
    if sleep:
        import time
        time.sleep(float(sleep))
    _count(counter)
    return b"TST1" + data

def decode(data):
    if not data.startswith(b"TST1"):
        raise ValueError("bad fixture frame")
    return data[4:]
"""

BAD_OUTPUT_ADAPTER = """
def encode(data, block_bytes, **options):
    return 123

def decode(data):
    return data
"""

RAW_MISMATCH_ADAPTER = """
def encode(data, block_bytes, **options):
    return b"TST1" + data

def decode(data):
    return b"not-the-source"
"""


class QuickbenchHarnessTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temp = tempfile.TemporaryDirectory(prefix="quickbench-test-")
        self.root = Path(self.temp.name)
        self.cache = self.root / "cache"
        self.runs = self.root / "runs"
        self.module = self.root / "adapter.py"
        self.module.write_text(textwrap.dedent(GOOD_ADAPTER), encoding="utf-8")
        self.counter = self.root / "encode-count"
        self.source = self.root / "source.bin"
        self.source.write_bytes(b"alpha\x00\xffbeta" * 17)
        self.codec = {
            "name": "fixture",
            "kind": "module",
            "module": str(self.module),
            "block_bytes": 31,
            "options": {"counter": str(self.counter)},
            "dependencies": [],
        }

    def tearDown(self) -> None:
        self.temp.cleanup()

    def _measure(self, name: str, *, codec: dict | None = None, cacheable: bool = False, timeout: float = 5.0):
        use_codec = dict(self.codec if codec is None else codec)
        return bench.measure(
            use_codec,
            bench.fingerprint(use_codec),
            self.source,
            self.runs / name,
            self.cache,
            timeout,
            0,
            cacheable,
        )

    def test_cache_miss_hit_redecodes_fresh_process_and_counts_once(self) -> None:
        first = self._measure("first", cacheable=True)
        second = self._measure("second", cacheable=True)
        self.assertFalse(first["cache_hit"])
        self.assertTrue(second["cache_hit"])
        self.assertIsNone(second["encode_process_ns"])
        self.assertEqual(self.counter.read_text(), "1")
        self.assertTrue(second["verified"])
        self.assertEqual(second["frame"]["sha256"], first["frame"]["sha256"])
        # The hit's decode logs are generated by a new worker process, not a
        # copied decoded artifact.
        verify = self.runs / "second" / "verify.stdout"
        self.assertTrue(verify.is_file())

    def test_corrupt_cache_is_quarantined_and_never_reported_as_hit(self) -> None:
        self._measure("first", cacheable=True)
        directories = [p for p in self.cache.iterdir() if p.is_dir()]
        self.assertEqual(len(directories), 1)
        cached_frame = directories[0] / "frame.bin"
        cached_frame.write_bytes(cached_frame.read_bytes() + b"corruption")
        with self.assertRaises(ValueError):
            self._measure("corrupt", cacheable=True)
        self.assertTrue(any(p.name.startswith(directories[0].name + ".invalid-") for p in self.cache.iterdir()))
        self.assertFalse((self.runs / "corrupt" / "frame.bin").exists())

    def test_stale_cache_identity_is_quarantined(self) -> None:
        self._measure("first", cacheable=True)
        directory = next(p for p in self.cache.iterdir() if p.is_dir())
        manifest = json.loads((directory / "record.json").read_text(encoding="utf-8"))
        manifest["identity"]["schema"] = 999
        (directory / "record.json").write_text(json.dumps(manifest), encoding="utf-8")
        with self.assertRaises(ValueError):
            self._measure("stale", cacheable=True)
        self.assertTrue(any(p.name.startswith(directory.name + ".invalid-") for p in self.cache.iterdir()))

    def test_coherently_tampered_cache_reaches_decode_check_and_is_quarantined(self) -> None:
        self._measure("first", cacheable=True)
        directory = next(p for p in self.cache.iterdir() if p.is_dir())
        frame = directory / "frame.bin"
        tampered = bytearray(frame.read_bytes())
        tampered[-1] ^= 1
        frame.write_bytes(tampered)
        manifest = json.loads((directory / "record.json").read_text(encoding="utf-8"))
        frame_record = bench.record(frame)
        frame_record["path"] = manifest["frame"]["path"]
        manifest["frame"] = frame_record
        (directory / "record.json").write_text(json.dumps(manifest), encoding="utf-8")
        with self.assertRaisesRegex(ValueError, "roundtrip mismatch"):
            self._measure("coherent-tamper", cacheable=True)
        self.assertFalse(directory.exists())
        self.assertTrue(any(p.name.startswith(directory.name + ".invalid-") for p in self.cache.iterdir()))

    def test_input_and_block_changes_make_distinct_content_keys(self) -> None:
        first = self._measure("first", cacheable=True)
        changed = self.root / "changed.bin"
        changed.write_bytes(self.source.read_bytes() + b"changed")
        changed_row = bench.measure(
            self.codec,
            bench.fingerprint(self.codec),
            changed,
            self.runs / "changed-input",
            self.cache,
            5.0,
            0,
            True,
        )
        block_codec = dict(self.codec, block_bytes=32)
        block_row = bench.measure(
            block_codec,
            bench.fingerprint(block_codec),
            self.source,
            self.runs / "changed-block",
            self.cache,
            5.0,
            0,
            True,
        )
        self.assertFalse(changed_row["cache_hit"])
        self.assertFalse(block_row["cache_hit"])
        self.assertNotEqual(first["frame"]["sha256"], changed_row["frame"]["sha256"])
        self.assertEqual(first["frame"]["sha256"], block_row["frame"]["sha256"])
        # The encoded bytes happen not to depend on block_bytes in this
        # fixture, but cache identity must still distinguish both changes.
        self.assertEqual(self.counter.read_text(), "3")
        cache_dirs = [p for p in self.cache.iterdir() if p.is_dir()]
        self.assertEqual(len(cache_dirs), 3)

    def test_candidate_is_never_cached_and_dependency_change_reencodes(self) -> None:
        first = self._measure("candidate-first", cacheable=False)
        dependency = self.root / "dep.txt"
        dependency.write_text("one", encoding="utf-8")
        changed_codec = dict(self.codec, dependencies=[str(dependency)])
        second = self._measure("candidate-second", codec=changed_codec, cacheable=False)
        self.assertFalse(first["cache_hit"])
        self.assertFalse(second["cache_hit"])
        self.assertEqual(self.counter.read_text(), "2")
        self.assertFalse(any(p.is_dir() for p in self.cache.iterdir()))
        dependency.write_text("two", encoding="utf-8")
        third = self._measure("candidate-third", codec=changed_codec, cacheable=False)
        self.assertEqual(self.counter.read_text(), "3")
        self.assertTrue(third["verified"])

    def test_unlisted_sibling_python_dependency_changes_provenance(self) -> None:
        helper = self.root / "helper.py"
        helper.write_text("MARKER = b'A'\n", encoding="utf-8")
        adapter = self.root / "dependent_adapter.py"
        adapter.write_text(
            """
from helper import MARKER
def encode(data, block_bytes, **options):
    return b'TST1' + MARKER + data
def decode(data):
    return data[5:]
""",
            encoding="utf-8",
        )
        codec = dict(self.codec, module=str(adapter), options={})
        before = bench.fingerprint(codec)
        helper.write_text("MARKER = b'B'\n", encoding="utf-8")
        after = bench.fingerprint(codec)
        self.assertNotEqual(before, after)

    def test_raw_mismatch_preserves_failure_logs_and_does_not_cache(self) -> None:
        bad = self.root / "mismatch.py"
        bad.write_text(textwrap.dedent(RAW_MISMATCH_ADAPTER), encoding="utf-8")
        codec = dict(self.codec, module=str(bad))
        with self.assertRaisesRegex(ValueError, "roundtrip mismatch"):
            self._measure("mismatch", codec=codec, cacheable=False)
        run = self.runs / "mismatch"
        self.assertTrue((run / "verify.stderr").is_file())
        self.assertTrue((run / "verify.command.json").is_file())
        self.assertEqual((run / "verify.stderr").read_text(encoding="utf-8"), "")
        self.assertFalse(any(p.is_dir() for p in self.cache.iterdir()))

    def test_timeout_and_adapter_type_failure_keep_logs(self) -> None:
        timeout_codec = dict(self.codec, options={"counter": str(self.counter), "sleep": 1})
        with self.assertRaises(subprocess.TimeoutExpired):
            self._measure("timeout", codec=timeout_codec, timeout=0.05)
        timeout_run = self.runs / "timeout"
        self.assertTrue((timeout_run / "encode.stderr").is_file())
        self.assertTrue((timeout_run / "encode.stdout").is_file())
        self.assertTrue((timeout_run / "encode.command.json").is_file())
        bad = self.root / "bad-output.py"
        bad.write_text(textwrap.dedent(BAD_OUTPUT_ADAPTER), encoding="utf-8")
        bad_codec = dict(self.codec, module=str(bad))
        with self.assertRaises(ValueError):
            self._measure("bad-output", codec=bad_codec, timeout=5.0)
        bad_run = self.runs / "bad-output"
        self.assertTrue((bad_run / "encode.stderr").is_file())
        self.assertIn("bytes", (bad_run / "encode.stderr").read_text(encoding="utf-8"))

    def test_preexisting_target_cannot_mask_encode_without_output(self) -> None:
        # A successful worker that exits without writing its target must not
        # let an old frame pass.  This uses a tiny alternate worker only to
        # exercise invoke()'s target-file contract; production code remains
        # untouched.
        stale_worker = self.root / "stale-worker.py"
        stale_worker.write_text(
            """
import pathlib
import sys
operation, _spec, source, target = sys.argv[1:5]
if operation == "encode":
    raise SystemExit(0)
pathlib.Path(target).write_bytes(pathlib.Path(source).read_bytes()[4:])
""",
            encoding="utf-8",
        )
        previous_worker = bench.WORKER
        previous_invoke = bench.invoke
        bench.WORKER = stale_worker
        def inject_stale(operation, spec, source, target, logs, timeout, timed):
            if operation == "encode":
                target.write_bytes(b"TST1" + self.source.read_bytes())
            return previous_invoke(operation, spec, source, target, logs, timeout, timed)
        bench.invoke = inject_stale
        try:
            with self.assertRaises(ValueError):
                self._measure("stale-target", cacheable=False)
        finally:
            bench.WORKER = previous_worker
            bench.invoke = previous_invoke
        stale_dir = self.runs / "stale-target"
        self.assertTrue((stale_dir / "encode.command.json").is_file())

    def test_timeout_kills_spawned_child_in_worker_process_group(self) -> None:
        marker = self.root / "child-survived"
        worker = self.root / "child-worker.py"
        worker.write_text(
            """
import json
import pathlib
import subprocess
import sys
import time
operation, spec, source, target = sys.argv[1:5]
if operation == 'encode':
    marker = json.loads(pathlib.Path(spec).read_text())['options']['marker']
    subprocess.Popen([sys.executable, '-c',
        'import pathlib,time; time.sleep(0.3); pathlib.Path(%r).write_text(\"survived\")' % marker])
    time.sleep(5)
else:
    pathlib.Path(target).write_bytes(pathlib.Path(source).read_bytes())
""",
            encoding="utf-8",
        )
        previous_worker = bench.WORKER
        bench.WORKER = worker
        try:
            codec = dict(self.codec, options={"marker": str(marker)})
            with self.assertRaises(subprocess.TimeoutExpired):
                self._measure("child-timeout", codec=codec, timeout=0.05)
        finally:
            bench.WORKER = previous_worker
        time.sleep(0.45)
        self.assertFalse(marker.exists())

    def test_frame_and_input_hashes_are_prefix_bytes_not_estimates(self) -> None:
        row = self._measure("hashes", cacheable=False)
        self.assertEqual(row["input"]["bytes"], len(self.source.read_bytes()))
        self.assertEqual(row["input"]["sha256"], bench.record(self.source)["sha256"])
        self.assertEqual(row["frame"]["bytes"], (self.runs / "hashes" / "frame.bin").stat().st_size)
        self.assertTrue(row["verified"])


if __name__ == "__main__":
    unittest.main()
